-- Flyway V001 — kran_auth (auth-service)
-- Legacy system had no admin user table.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE admin_user (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username            VARCHAR(128) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    display_name        VARCHAR(255),
    is_active           BOOLEAN NOT NULL DEFAULT true,
    last_login_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_admin_user_username UNIQUE (username)
);

CREATE TABLE admin_login_audit (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id       UUID REFERENCES admin_user (id),
    success             BOOLEAN NOT NULL,
    ip_address          INET,
    user_agent          VARCHAR(512),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_login_audit_user ON admin_login_audit (admin_user_id, created_at DESC);
