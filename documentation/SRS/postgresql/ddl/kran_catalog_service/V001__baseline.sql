-- Flyway V001 — kran_catalog (catalog-service)

CREATE TABLE category (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    type                VARCHAR(50),
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);

CREATE TABLE casestudy (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category            VARCHAR(255),
    title               VARCHAR(500),
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    posted_on           TIMESTAMPTZ,
    posted_by           VARCHAR(128),
    image_path          VARCHAR(500),
    attachment_path     VARCHAR(500),
    link                VARCHAR(500),
    blog_banner         VARCHAR(500),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);

CREATE TABLE project_product (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(1000),
    title               VARCHAR(5000),
    description         TEXT,
    type                VARCHAR(20),
    logo                VARCHAR(255),
    active_status       VARCHAR(2) NOT NULL DEFAULT 'Y',
    category            VARCHAR(150),
    order_no            INTEGER,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);

CREATE INDEX idx_project_product_order ON project_product (order_no)
    WHERE deleted_at IS NULL;

