-- Flyway V001 — kran_media (media-service)

CREATE TABLE gallgroup (
    group_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(255),
    posted_on           TIMESTAMPTZ,
    image_path          VARCHAR(500),
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);

CREATE TABLE gallery (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(255),
    posted_on           TIMESTAMPTZ,
    image_path          VARCHAR(500),
    group_id            BIGINT NOT NULL,
    type                VARCHAR(50),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128),
    CONSTRAINT fk_gallery_group FOREIGN KEY (group_id)
        REFERENCES gallgroup (group_id) ON DELETE RESTRICT
);

CREATE INDEX idx_gallery_group_id ON gallery (group_id)
    WHERE deleted_at IS NULL;
