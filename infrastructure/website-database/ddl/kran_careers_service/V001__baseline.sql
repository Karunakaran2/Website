-- Flyway V001 — kran_careers (careers-service)

CREATE TABLE careers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(255),
    job_description     TEXT,
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    posted_on           TIMESTAMPTZ,
    last_date           TIMESTAMPTZ,
    skill_set           VARCHAR(255),
    location            VARCHAR(255),
    experience          VARCHAR(255),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);

CREATE INDEX idx_careers_active ON careers (posted_on DESC)
    WHERE deleted_at IS NULL AND active_status = 'Y';

CREATE TABLE application_request (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    career_id           BIGINT,
    name                VARCHAR(150),
    email               VARCHAR(255),
    mobile              VARCHAR(20),
    resume_path         VARCHAR(500),
    submitted_on        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_application_career FOREIGN KEY (career_id)
        REFERENCES careers (id) ON DELETE RESTRICT
);

CREATE INDEX idx_application_career ON application_request (career_id);
CREATE INDEX idx_application_submitted ON application_request (submitted_on DESC);

CREATE TABLE submitted_resumes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150),
    email               VARCHAR(255),
    mobile              VARCHAR(20),
    exp                 VARCHAR(255),
    intro               TEXT,
    resume_path         VARCHAR(500),
    submitted_on        TIMESTAMPTZ NOT NULL DEFAULT now(),
    role                VARCHAR(255)
);

CREATE INDEX idx_submitted_resumes_on ON submitted_resumes (submitted_on DESC);
