-- Flyway V001 — kran_content (content-service)
-- PostgreSQL 15+

CREATE TABLE news (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(255) NOT NULL,
    news_description    TEXT,
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    posted_on           TIMESTAMPTZ,
    publish_date        TIMESTAMPTZ,
    image_path          VARCHAR(500),
    news_link           VARCHAR(500),
    read_more_type      VARCHAR(50),
    pdf_path            VARCHAR(500),
    type                VARCHAR(50),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128),
    CONSTRAINT chk_news_active_status CHECK (active_status IN ('Y', 'N'))
);

CREATE INDEX idx_news_publish_active ON news (publish_date DESC)
    WHERE deleted_at IS NULL AND active_status = 'Y';

CREATE TABLE banner (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    image_path          VARCHAR(500),
    order_no            INTEGER,
    heading             VARCHAR(255),
    title               VARCHAR(255),
    link                VARCHAR(500),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);

CREATE INDEX idx_banner_order ON banner (order_no)
    WHERE deleted_at IS NULL AND active_status = 'Y';

CREATE TABLE blog (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category            VARCHAR(255),
    title               VARCHAR(500) NOT NULL,
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    posted_on           TIMESTAMPTZ,
    posted_by           VARCHAR(128),
    image_path          VARCHAR(500),
    attachment_path     VARCHAR(500),
    link                VARCHAR(500),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);

CREATE INDEX idx_blog_posted ON blog (posted_on DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE kran_timeline (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(255),
    heading             VARCHAR(255),
    description         TEXT,
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    submitted_on        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);
