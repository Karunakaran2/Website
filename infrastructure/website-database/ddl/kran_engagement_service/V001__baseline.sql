-- Flyway V001 — kran_engagement (engagement-service)

CREATE TABLE contacts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(500) NOT NULL,
    email               VARCHAR(300) NOT NULL,
    mobile              VARCHAR(20) NOT NULL,
    organization        VARCHAR(500),
    remarks             TEXT,
    request_type        CHAR(1) NOT NULL,
    product_name        VARCHAR(255),
    submitted_on        TIMESTAMPTZ NOT NULL DEFAULT now(),
    archived_at         TIMESTAMPTZ,
    CONSTRAINT chk_contacts_request_type CHECK (request_type IN ('G','B','D','T','E','C'))
);

CREATE INDEX idx_contacts_submitted ON contacts (submitted_on DESC);
CREATE INDEX idx_contacts_type ON contacts (request_type);

CREATE TABLE comments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comments            TEXT,
    blog_id             BIGINT NOT NULL,
    comment_id          BIGINT,
    posted_on           TIMESTAMPTZ NOT NULL DEFAULT now(),
    posted_by           VARCHAR(128),
    CONSTRAINT fk_comments_parent FOREIGN KEY (comment_id)
        REFERENCES comments (id) ON DELETE SET NULL
);

CREATE INDEX idx_comments_blog ON comments (blog_id, posted_on DESC);
