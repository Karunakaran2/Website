-- Flyway V001 — kran_notification (notification-service)

CREATE TABLE mail_setup (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                VARCHAR(10) NOT NULL,
    mail_to             VARCHAR(1000),
    mail_cc             VARCHAR(1000),
    added_on            TIMESTAMPTZ,
    active_status       VARCHAR(1) NOT NULL DEFAULT 'Y',
    deactivated_on      TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(128),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(128),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(128)
);

CREATE UNIQUE INDEX uq_mail_setup_type_active ON mail_setup (type)
    WHERE deleted_at IS NULL AND active_status = 'Y';

CREATE TABLE outbound_email_log (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correlation_id      UUID NOT NULL DEFAULT gen_random_uuid(),
    template_code       VARCHAR(64),
    recipient           VARCHAR(255) NOT NULL,
    status              VARCHAR(20) NOT NULL,
    error_message       TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_email_log_status CHECK (status IN ('SENT', 'FAILED', 'QUEUED'))
);

CREATE INDEX idx_email_log_created ON outbound_email_log (created_at DESC);
