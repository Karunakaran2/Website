CREATE TABLE admin_audit_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_user_id   UUID REFERENCES admin_user (id) ON DELETE SET NULL,
    actor_username  VARCHAR(128) NOT NULL,
    action          VARCHAR(64) NOT NULL,
    module_key      VARCHAR(64) NOT NULL,
    entity_type     VARCHAR(64),
    entity_id       VARCHAR(128),
    summary         VARCHAR(512),
    ip_address      VARCHAR(45),
    user_agent      VARCHAR(512)
);

CREATE INDEX idx_admin_audit_occurred ON admin_audit_event (occurred_at DESC);
CREATE INDEX idx_admin_audit_actor ON admin_audit_event (actor_user_id, occurred_at DESC);
CREATE INDEX idx_admin_audit_module ON admin_audit_event (module_key, occurred_at DESC);

