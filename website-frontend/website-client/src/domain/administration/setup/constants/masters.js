export function resolveSetupMaster(primaryId, secondaryId) {
  if (primaryId === SETUP_BANK_CASH_ID) {
    return SETUP_MASTERS[secondaryId] || SETUP_MASTERS.bank
  }
  if (primaryId === SETUP_PARTY_ID) {
    return SETUP_MASTERS[secondaryId] || SETUP_MASTERS['add-new']
  }
  if (primaryId === SETUP_ALLOCATION_ID) {
    return SETUP_MASTERS[secondaryId] || SETUP_MASTERS['ledger-allocation']
  }
  if (primaryId === SETUP_OPENING_BALANCE_ID) {
    return SETUP_MASTERS[secondaryId] || SETUP_MASTERS['ledger-opening-balance']
  }
  if (primaryId === SETUP_FINANCIAL_YEAR_ID) {
    return SETUP_MASTERS[secondaryId] || SETUP_MASTERS['fin-closure']
  }
  if (primaryId === SETUP_APPROVAL_ID) {
    return { key: 'approval', inbox: secondaryId || 'received' }
  }
  return SETUP_MASTERS[primaryId] || null
}
