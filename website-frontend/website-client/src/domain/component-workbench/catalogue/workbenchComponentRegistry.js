export function getCatalogStats(catalog = WORKBENCH_COMPONENT_CATALOG) {
  const byStatus = {}
  const byCategory = {}
  for (const entry of catalog) {
    byStatus[entry.demoStatus] = (byStatus[entry.demoStatus] || 0) + 1
    byCategory[entry.category] = (byCategory[entry.category] || 0) + 1
  }
  const interactiveOrGrouped = catalog.filter(
    (e) => e.demoStatus === 'interactive' || e.demoStatus === 'grouped',
  ).length
  const withRoute = catalog.filter((e) => e.routeKey).length
  const missingPreview = catalog.filter(
    (e) => e.demoStatus === 'docs-only' || e.demoStatus === 'partial' || e.demoStatus === 'not-in-repo',
  )
  return {
    total: catalog.length,
    categories: WORKBENCH_CATALOG_CATEGORIES.length,
    interactiveOrGrouped,
    withRoute,
    byStatus,
    byCategory,
    missingPreviewCount: missingPreview.length,
    missingPreview,
  }
}

/**
 * @param {string} query
 * @param {WorkbenchCatalogEntry[]} [catalog]
 */
export function searchWorkbenchCatalog(query, catalog = WORKBENCH_COMPONENT_CATALOG) {
  const q = query.trim().toLowerCase()
  if (!q) return catalog
  return catalog.filter((entry) => {
    const haystack = [
      entry.name,
      entry.description,
      entry.purpose,
      entry.importPath ?? '',
      ...(entry.keywords ?? []),
    ]
      .join(' ')
      .toLowerCase()
    return haystack.includes(q)
  })
}

export function getCategoryLabel(categoryId) {
  return WORKBENCH_CATALOG_CATEGORIES.find((c) => c.id === categoryId)?.label ?? categoryId
}
